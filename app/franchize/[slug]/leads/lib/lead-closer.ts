// ── Типы ───────────────────────────────────────────────────────────────────

export type CloserStepKey = "clarify" | "label" | "overview" | "sell" | "explain" | "reinforce";

export interface CloserStep {
  key: CloserStepKey;
  emoji: string;
  /** Название шага для оператора («Выясни, зачем пришёл»). */
  title: string;
  /** Зачем шаг — принцип Хормози одной строкой. */
  goal: string;
  /** Готовые фразы оператора (аренда мото, наш контекст). */
  moves: string[];
}

export type ObjectionKey =
  | "money"
  | "stall"
  | "timing"
  | "past"
  | "decision"
  | "preference";

export interface CloserObjection {
  key: ObjectionKey;
  emoji: string;
  /** Как оператор это называет («Дорого»). */
  label: string;
  /** Что обычно говорит покупатель. */
  trigger: string;
  /** Приём Хормози для этого типа. */
  principle: string;
  /** Готовый ответ оператора (копируется кнопкой). */
  response: string;
}

export interface CloserObjectionHit {
  objection: CloserObjection;
  /** Почему подсказали: «в сообщении: „дорого"» / null — типовое. */
  reason: string | null;
}

export interface CloserCoach {
  /** Шаги разговора: все 6 — или один «reinforce», если сделка закрыта. */
  steps: readonly CloserStep[];
  /** Возражения, ранжированные по сигналам (топ-3; без сигналов — типовые 2). */
  objections: CloserObjectionHit[];
  /** true — сделка уже есть: показываем только «закрепи решение». */
  reinforceOnly: boolean;
}

