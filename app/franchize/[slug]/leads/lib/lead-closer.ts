/** Топ-2 дефолта, когда сигналов нет: «дорого» и «подумаю» — самые частые. */
const DEFAULT_OBJECTIONS: readonly ObjectionKey[] = ["money", "stall"];

const MAX_TOP_OBJECTIONS = 3;

function firstSignal(text: string, words: string[]): string | null {
  for (const w of words) {
    if (text.includes(w)) return w;
  }
  return null;
}

// ── Контекстная шпаргалка ──────────────────────────────────────────────────

/** Маппинг «возражение AI-агента» (analysis.objection) → ключ карточки
 *  CLOSER. Агент размечает тон сообщений (price/license/experience/trust);
 *  его сигнал приоритетнее локальных keyword-сигналов: он видит ВЕСЬ чат. */
const AI_OBJECTION_MAP: Readonly<Record<string, ObjectionKey>> = {
  price: "money",
  license: "preference",
  experience: "past",
  trust: "stall",
};

/**
 * Шпаргалка разговора по лиду: 6 шагов CLOSER + возражения, ранжированные
 * по сигналам (1) возражение AI-агента из analysis (весь чат), (2) ключевые
 * слова первого/последнего сообщения. Конвертированный лид — только шаг
 * «закрепи решение» (R): остальные шаги уже позади. Возвращает null для
 * операторских заглушек — секция не рендерится.
 */
export function buildCloserCoach(leadInput: LeadRow): CloserCoach | null {
  const lead = ensureLeadArraysSafe(leadInput);
  if (lead.identityState === "operator_placeholder") return null;

  const reinforceStep = CLOSER_STEP_BY_KEY.reinforce;

  const isConverted =
    lead.rentals.length > 0 || lead.sales.length > 0 || (lead.contractCount ?? 0) > 0;
  if (isConverted) {
    return { steps: [reinforceStep], objections: [], reinforceOnly: true };
  }

  const hits: CloserObjectionHit[] = [];
  const seen = new Set<ObjectionKey>();
  const pushHit = (key: ObjectionKey, reason: string | null) => {
    if (seen.has(key)) return;
    seen.add(key);
    hits.push({ objection: CLOSER_OBJECTION_BY_KEY[key], reason });
  };

  // 1) AI-агент: возражение размечено по всему чату — приоритетный сигнал.
  const aiObjection = lead.avito?.analysis?.objection ?? null;
  const aiKey = aiObjection ? AI_OBJECTION_MAP[aiObjection] : undefined;
  if (aiKey) pushHit(aiKey, `AI-агент отметил: ${aiObjection}`);

  // 2) Локальные keyword-сигналы по тексту покупателя.
  const avito = lead.avito;
  const text = `${avito?.firstMessage ?? ""} ${avito?.lastMessage ?? ""}`
    .toLowerCase()
    .replace(/\s+/g, " ");
  for (const { key, words } of OBJECTION_SIGNALS) {
    const word = firstSignal(text, words);
    if (word) pushHit(key, `в сообщении: «${word}»`);
  }

  // 3) Дефолт: самые частые возражения («дорого», «подумаю»), без «почему».
  if (hits.length === 0) {
    for (const key of DEFAULT_OBJECTIONS) pushHit(key, null);
  }

  return {
    steps: CLOSER_STEPS,
    objections: hits.slice(0, MAX_TOP_OBJECTIONS),
    reinforceOnly: false,
  };
}
