// — OFF-the-call; «Готовый ответ» (lead-scripts.ts) — точечные ответы
// по интенту; этот модуль — третий кусок: КАК вести сам разговор.
//
// C — Clarify   «Почему вы с нами?» — интерес уже есть (написал/оставил
//               заявку), осталось спросить почему: «you just ask them why».
// L — Label     Верни сказанное своими словами: «repeat back what they just
//               said» — активное слушание строит доверие лучше аргументов.
// O — Overview  Цикл боли: «что уже пробовали? как получилось?» — не для
//               допроса, а чтобы клиент сам вспомнил цену бездействия
//               («deprivation creates motivation») и чтобы собрать дозор:
//               что понравилось — продаём это, что нет — не предлагаем.
// S — Sell the  Продай МАУИ, а не рейс: «people don't buy drills, they buy
//   vacation   holes». Три столпа питч-а (по три: «three just always
//               worked») + одна история к каждому столпу.
// E — Explain   Шесть типов «нет»: время (приоритеты), предпочтения
//   away       (их способ ≠ наш результат), деньги (логика+доказательства+
//               условия), «подумаю» (логическое решение+страх), прошлый
//               опыт («хуже плохой инвестиции только дать ей помешать
//               хорошей»), лицо, принимающее решение (разрешение vs
//               поддержка).
// R — Reinforce Закрепи решение: «we have to bridge this… reinforce that
//               they made a great call» — тёплый хэндофф: что дальше,
//               шаги 1-2-3, кто на связи.
//
// Модуль чистый: без React, без Date.now(). Фразы — готовые, в тоне
// экипажа VIP BIKE (аренда электро/бензин мото, Н. Новгород). buildCloser
// поднимает релевантные возражения по сигналам сообщений лида — «почему
// подсказали», а не угадайка.

import type { LeadRow } from "../leads-types";
