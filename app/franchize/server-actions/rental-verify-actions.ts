export async function resendVerificationDmsAction(params: {
  slug: string;
  rentalId: string;
  /** Password-auth path (PC viewer): owner id from validateAnalyticsPassword. */
  actorUserId?: string;
  /** Password-auth path flag — must come with actorUserId. */
  isPasswordAuth?: boolean;
}): Promise<ActionResponse<ResendDmsResult>> {
  try {
    const actor = await resolveVerifyOwnerActor({
      slug: params.slug,
      actorUserId: params.actorUserId,
      isPasswordAuth: params.isPasswordAuth,
      ownerOnlyError: "Выслать сверку может владелец или администратор экипажа.",
    });
    if (!actor.ok) return { success: false, error: actor.error };
    const actorChatId = String(actor.actorChatId || "");

    const { data: rentalRow, error: rentalError } = await supabaseAdmin
      .from("rentals")
      .select(`
        rental_id, crew_id, owner_id, total_cost, metadata, status,
        deposit_amount, deposit_returned,
        created_by_operator_chat_id, created_at,
        requested_start_date, requested_end_date, agreed_start_date, agreed_end_date,
        start_photo_count, end_photo_count,
        vehicle:cars(id, make, model, specs, daily_price, type, crew_id, is_test_result)
      `)
      .eq("rental_id", params.rentalId)
      .maybeSingle();
    if (rentalError) throw rentalError;
    const rental = rentalRow as any;
    if (!rental) return { success: false, error: "Аренда не найдена." };
    if (rental.status !== "completed") {
      return { success: false, error: "Сверка отправляется по закрытым арендам." };
    }

    const { row, created } = await loadOrCreateVerificationRow({
      rental,
      actorChatId,
      source: "admin_resend",
      fallbackSlug: params.slug,
    });

    // HEAL 2026-10-20: task111 backfill rows (44 шт.) carry operator_chat_id =
    // NULL (old rentals without created_by_operator_chat_id) — resend reached
    // only the owner and the operator could never ✅. Re-resolve via the
    // canonical chain (same ±25h shift idiom as requestRentalVerification)
    // and patch the row so the state machine sees both parties again.
    const ownerChatId = row.owner_chat_id ? String(row.owner_chat_id) : null;
    let operatorChatId = row.operator_chat_id ? String(row.operator_chat_id) : null;
    if (!operatorChatId) {
      try {
        const createdAtMs = Date.parse(String(rental.created_at || "")) || Date.now();
        const { data: shiftRows } = await supabaseAdmin
          .from("crew_member_shifts")
          .select("member_id, clock_in_time, clock_out_time")
          .eq("crew_id", rental.crew_id)
          .gte("clock_in_time", new Date(createdAtMs - 25 * 3600 * 1000).toISOString())
          .lte("clock_in_time", new Date(createdAtMs + 25 * 3600 * 1000).toISOString());
        const shifts: ShiftLike[] = (shiftRows || []).map((s: any) => ({
          member_id: s.member_id,
          clock_in_time: s.clock_in_time,
          clock_out_time: s.clock_out_time ?? null,
        }));
        const attribution = resolveRentalOperator(
          {
            created_by_operator_chat_id: rental.created_by_operator_chat_id,
            created_at: rental.created_at,
            metadata: rental.metadata,
          },
          shifts,
        );
        const healed = attribution.operatorId ? String(attribution.operatorId) : null;
        if (healed && healed !== ownerChatId) {
          const { error: patchErr } = await supabaseAdmin
            .from("rental_verifications")
            .update({ operator_chat_id: healed })
            .eq("rental_id", row.rental_id);
          if (!patchErr) {
            operatorChatId = healed;
            row.operator_chat_id = healed;
            logger.info(`[rental-verify] healed operator_chat_id=${healed} for ${row.rental_id} (was NULL)`);
          } else {
            logger.warn(`[rental-verify] operator heal patch failed for ${row.rental_id}:`, patchErr);
          }
        }
      } catch (healErr) {
        logger.warn(`[rental-verify] operator heal skipped for ${row.rental_id} (non-fatal):`, healErr);
      }
    }

    const usersMap = await loadUsersMap([operatorChatId, ownerChatId, actorChatId]);
    const operatorLabel = labelFromUsersMap(usersMap, operatorChatId);
    const ownerLabel = labelFromUsersMap(usersMap, ownerChatId);
    const singleParty = !operatorChatId || operatorChatId === ownerChatId;
    const summary = formatVerificationSummary({
      crewName: row.crew_slug,
      snapshot: row.snapshot as any,
      usersMap,
      operatorChatId: row.operator_chat_id,
      ownerChatId: row.owner_chat_id,
      statusNote: verificationStatusNote({
        status: row.status,
        singleParty,
        operatorLabel,
        ownerLabel,
      }),
    });
    // Task 156 (boss 2026-10-28: «перевысылаем уже подтверждённую сверку — кнопок
    // нет; завершенные тоже разрешить перередактировать, переоткрыть»): every
    // resend now carries a keyboard. Verified rows get the 🔁 reopen button
    // (vrf_dis_ — the state machine clears the stamps and opens the split
    // editor); disputed rows get the standard ✅/⚠️ pair back (⚠️ re-enters the
    // editor, ✅ closes the спор when the other side has already confirmed).
    const keyboard =
      row.status === "verified"
        ? verificationReopenKeyboard(row.rental_id)
        : verificationKeyboard(row.rental_id);
    const withKeyboard = keyboard.length > 0;

    const sentTo: string[] = [];
    const failed: Array<{ chatId: string; error: string }> = [];
    const recipients = [...new Set([operatorChatId, ownerChatId].filter(Boolean) as string[])];
    for (const chatId of recipients) {
      try {
        const res = await sendComplexMessage(chatId, summary, keyboard, { parseMode: "HTML", keyboardType: "inline" });
        if (res?.success !== false) sentTo.push(chatId);
        else failed.push({ chatId, error: res?.error || "Telegram API error" });
      } catch (e) {
        const msg = e instanceof Error ? e.message : String(e);
        logger.warn(`[rental-verify] resend DM failed for ${chatId} (rental ${row.rental_id}):`, e);
        failed.push({ chatId, error: msg });
      }
    }

    // boss 2026-10-20: the presser must SEE the result. Parties are operator +
    // owner — the clicking admin is often NEITHER (e.g. the boss resending on
    // vip-bike, where the owner is Ilya and the operator is DJORUDJOV): both
    // DMs landed fine, the toast said «(2 получено) ✅», and the boss still got
    // NOTHING (actor is also excluded from the staff cc). Task 118: the proof
    // copy now carries the ✅/⚠️ keyboard — crew staff are first-class actors
    // in the TG machine (admin ✅ verifies instantly), so the boss can settle
    // the сверка right from the copy. The old keyboardless-copy comment is
    // history.
    let actorCopied = false;
    if (actorChatId && !recipients.includes(actorChatId)) {
      const who = recipients.length
        ? recipients.map((c) => labelFromUsersMap(usersMap, c)).join(", ")
        : "получатели не найдены";
      const proof = `📤 <b>Копия сверки</b> (вы высылали · получатели: ${who})\n\n${summary}`;
      try {
        const res = await sendComplexMessage(
          actorChatId,
          proof,
          withKeyboard ? verificationKeyboard(row.rental_id) : [],
          { parseMode: "HTML", keyboardType: "inline" },
        );
        actorCopied = res?.success !== false;
        if (!actorCopied) failed.push({ chatId: actorChatId, error: `копия: ${res?.error || "Telegram API error"}` });
      } catch (e) {
        logger.warn(`[rental-verify] actor proof copy failed for ${actorChatId} (rental ${row.rental_id}):`, e);
      }
    }
    logger.info(`[rental-verify] DMs resent for ${row.rental_id} by ${actorChatId} (created=${created}, sent=${sentTo.length}/${recipients.length}, actorCopied=${actorCopied}, status=${row.status})`);

    // VF-FIX 2026-10-18: when this resend CREATED the row (rental closed
    // before the trigger fix / lost to the ~10s tail), the staff cc from
    // requestRentalVerification never happened — send it now. Pure resends
    // of an already-announced verification stay party-only (no re-noise).
    if (created) {
      try {
        const { ccVerificationToCrewStaff } = await import("@/app/franchize/lib/rental-verify");
        await ccVerificationToCrewStaff({
          crewSlug: row.crew_slug || params.slug,
          rentalId: row.rental_id,
          summary,
          exclude: [row.operator_chat_id, row.owner_chat_id, actorChatId],
        });
      } catch (ccErr) {
        logger.warn("[rental-verify] resend staff cc failed (non-fatal):", ccErr);
      }
    }

    // Honest result: parties delivered → success (with per-chat failures if
    // partial). Nothing delivered → ERROR with the reasons; the actor proof
    // copy above still went out so the presser sees what happened.
    if (recipients.length === 0) {
      return errorResponse(
        `Получатели не найдены — в строке сверки нет ни оператора, ни владельца.${actorCopied ? " Копия выслана вам." : ""}`,
      );
    }
    if (sentTo.length === 0) {
      return errorResponse(
        `Telegram не доставил сверку: ${failed.map((f) => `${f.chatId}: ${f.error}`).join("; ")}.${actorCopied ? " Копия выслана вам." : ""}`,
      );
    }
    return successResponse({ rentalId: row.rental_id, sentTo, failed, created, status: row.status, actorCopied });
  } catch (err: any) {
    logger.error("[rental-verify] resendVerificationDmsAction exception:", err);
    const friendly = typeof err?.message === "string" && err.message.includes("Таблица сверок")
      ? err.message
      : handleError(err, "resendVerificationDmsAction");
    return errorResponse(friendly);
  }
}

// ── VF-FIX 2026-10-18: bulk FINE confirm (the backlog verifier) ─────────────
// WHY: the Aug/Sep/Oct backfill (docs/crewDocs/rental-verifications-backfill-
// aug-oct-2026-10-18.sql) creates pending verification rows for every closed
// rental, each snapshot carrying snapshot.audit = { grade, notes } from the
// audit script (fine / almost / sus). Confirming ~200 fine rows one drawer
// tap at a time is a waste of the boss's evening — this action verifies a
// MONTH's fine-graded pending rows in one owner-tier tap.
//
// SAFETY:
//   • owner/co_owner/admin only (same gate as adminVerifyRentalAction);
//   • ONLY rows with snapshot.audit.grade === 'fine' — almost/sus need human
//     eyes and are never touched here (they are reported back as skipped);
//   • ONLY pending rows (verified/disputed are left alone);
//   • dryRun=true (the default first step) returns the list WITHOUT writing;
//   • each row goes through the SAME applyVerificationAction state machine
//     + optimistic .eq(status,'pending') guard as the single action, so a
//     concurrent party tap cannot be clobbered.
export interface BulkVerifyFineResult {
  month: string;
  dryRun: boolean;
  candidates: Array<{
    rentalId: string;
    bikeName: string;
    totalCost: number | null;
    grade: string;
    notes: string[];
  }>;
  skippedNotFine: number;
  applied: number;
  failed: number;
}

export async function bulkVerifyFineAction(params: {
  slug: string;
  /** MSK month, 'YYYY-MM' (the analytics month the boss is looking at). */
  month: string;
  dryRun?: boolean;
  /** Password-auth path (PC viewer): owner id from validateAnalyticsPassword. */
  actorUserId?: string;
  /** Password-auth path flag — must come with actorUserId. */
  isPasswordAuth?: boolean;
}): Promise<ActionResponse<BulkVerifyFineResult>> {
  try {
    const actor = await resolveVerifyOwnerActor({
      slug: params.slug,
      actorUserId: params.actorUserId,
      isPasswordAuth: params.isPasswordAuth,
      ownerOnlyError: "Массовое подтверждение доступно владельцу или администратору экипажа.",
    });
    if (!actor.ok) return { success: false, error: actor.error };
    const actorChatId = String(actor.actorChatId || "");
    if (!/^\d{4}-\d{2}$/.test(params.month)) {
      return { success: false, error: "Неверный формат месяца (ожидается ГГГГ-ММ)." };
    }

    // Pending rows of this crew; the MSK-month filter happens in JS off the
    // rental's requested_start_date (snapshot has no month field on purpose).
    const { data: rows, error: rowsError } = await supabaseAdmin
      .from("rental_verifications")
      .select("rental_id, status, snapshot, operator_chat_id, owner_chat_id")
      .eq("crew_slug", params.slug)
      .eq("status", "pending")
      .limit(500);
    if (rowsError) {
      const msg = rowsError.message || "";
      if (rowsError.code === "42P01" || /relation .* does not exist/i.test(msg)) {
        return { success: false, error: "Таблица сверок ещё не создана — примените SQL (rental-verifications-table-2026-10-17.sql)." };
      }
      throw rowsError;
    }
    const pendingRows = (rows || []) as Array<{
      rental_id: string;
      status: string;
      snapshot: Record<string, unknown> | null;
      operator_chat_id: string | null;
      owner_chat_id: string | null;
    }>;
    if (pendingRows.length === 0) {
      return successResponse({ month: params.month, dryRun: params.dryRun !== false, candidates: [], skippedNotFine: 0, applied: 0, failed: 0 });
    }

    // MSK month window over the rentals' requested_start_date.
    const [y, m] = params.month.split("-").map(Number);
    const startUtc = new Date(Date.UTC(y, m - 1, 1, 0, 0, 0) - 3 * 3600 * 1000);
    const endUtc = new Date(Date.UTC(y, m, 1, 0, 0, 0) - 3 * 3600 * 1000);
    const { data: rentals, error: rentalsError } = await supabaseAdmin
      .from("rentals")
      .select("rental_id, requested_start_date, agreed_start_date")
      .in("rental_id", pendingRows.map((r) => r.rental_id))
      .gte("requested_start_date", startUtc.toISOString())
      .lt("requested_start_date", endUtc.toISOString());
    if (rentalsError) throw rentalsError;
    const monthIds = new Set((rentals || []).map((r: any) => String(r.rental_id)));

    const candidates: BulkVerifyFineResult["candidates"] = [];
    let skippedNotFine = 0;
    for (const row of pendingRows) {
      if (!monthIds.has(row.rental_id)) continue;
      const audit = (row.snapshot?.audit ?? null) as { grade?: string; notes?: string[] } | null;
      if (audit?.grade !== "fine") {
        skippedNotFine += 1;
        continue;
      }
      const snap = (row.snapshot || {}) as { bikeName?: string; totalCost?: number | null };
      candidates.push({
        rentalId: row.rental_id,
        bikeName: String(snap.bikeName || "аренда"),
        totalCost: typeof snap.totalCost === "number" ? snap.totalCost : null,
        grade: "fine",
        notes: Array.isArray(audit.notes) ? audit.notes.map(String) : [],
      });
    }

    const dryRun = params.dryRun !== false;
    if (dryRun) {
      return successResponse({ month: params.month, dryRun: true, candidates, skippedNotFine, applied: 0, failed: 0 });
    }

    // Apply — boss-confirms-for-the-pair semantics, same as the single action.
    const nowIso = new Date().toISOString();
    let applied = 0;
    let failed = 0;
    for (const row of pendingRows) {
      if (!candidates.some((c) => c.rentalId === row.rental_id)) continue;
      const fakeRow = {
        rental_id: row.rental_id,
        status: "pending",
        operator_chat_id: row.operator_chat_id,
        owner_chat_id: row.owner_chat_id,
      } as unknown as RentalVerificationRow;
      const stateChatId =
        row.operator_chat_id === actorChatId || row.owner_chat_id === actorChatId
          ? actorChatId
          : row.owner_chat_id || actorChatId;
      const result = applyVerificationAction(fakeRow, { action: "confirm", chatId: stateChatId, nowIso });
      if (!result.row) {
        failed += 1;
        continue;
      }
      const { error: updateError } = await supabaseAdmin
        .from("rental_verifications")
        .update({
          status: "verified",
          operator_confirmed_at: result.row.operator_confirmed_at ?? nowIso,
          owner_confirmed_at: result.row.owner_confirmed_at ?? nowIso,
          verified_at: result.row.verified_at ?? nowIso,
          updated_at: nowIso,
        })
        .eq("rental_id", row.rental_id)
        .eq("status", "pending"); // optimistic lock — a concurrent party tap wins
      if (updateError) {
        logger.warn(`[rental-verify] bulk verify update failed for ${row.rental_id}:`, updateError);
        failed += 1;
      } else {
        applied += 1;
      }
    }
    logger.info(`[rental-verify] bulk fine verify ${params.month}/${params.slug} by ${actorChatId}: applied=${applied} failed=${failed} skippedNotFine=${skippedNotFine}`);
    return successResponse({ month: params.month, dryRun: false, candidates, skippedNotFine, applied, failed });
  } catch (err: any) {
    logger.error("[rental-verify] bulkVerifyFineAction exception:", err);
    return errorResponse(handleError(err, "bulkVerifyFineAction"));
  }
}

