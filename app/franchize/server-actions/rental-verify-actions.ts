// ── Password-auth path for the verify family (task151) ─────────────────────
// The analytics page opened on PC via the emailed /analytics_pass password
// has NO Telegram actor cookie — verifyCrewAccess bounces with «Не
// авторизовано.» and every owner-tier verify affordance (table ✓, drawer
// card, bulk sweeps, verification round) died with that toast. The password
// session acts as the CREW OWNER: the validate_analytics_password RPC hands
// out crews.owner_id, the client echoes it back, and the server re-gates it
// against the DB (same contract as leads.ts verifyCrewOwnerAccess /
// rentals-dashboard.ts verifyPasswordAuthOwner — only the real owner, or a
// global admin, would know that id).
async function verifyPasswordAuthOwnerAccess(
  slug: string,
  actorUserId: string,
): Promise<{ ok: boolean; error?: string }> {
  if (!actorUserId) return { ok: false, error: "Не удалось определить пользователя." };
  const { data: crew } = await supabaseAdmin
    .from("crews")
    .select("id, owner_id")
    .eq("slug", slug)
    .maybeSingle();
  if (!crew) return { ok: false, error: "Экипаж не найден." };
  if (crew.owner_id === actorUserId) return { ok: true };
  // Global-admin fallback (a password generated by an admin for a crew they
  // don't own) — both storage locations, same as resolveRentalsAccess.
  const { data: user } = await supabaseAdmin
    .from("users")
    .select("role, status, metadata")
    .eq("user_id", actorUserId)
    .maybeSingle();
  const meta = (user?.metadata || {}) as Record<string, unknown>;
  const isGlobalAdmin =
    user?.role === "admin" ||
    user?.role === "vprAdmin" ||
    user?.status === "admin" ||
    meta?.role === "admin" ||
    meta?.status === "admin";
  return isGlobalAdmin
    ? { ok: true }
    : { ok: false, error: "Недостаточно прав." };
}

/**
 * Resolves the acting identity for owner-tier verify actions across BOTH
 * auth paths, in priority order:
 *   1. signed Telegram actor cookie (web app) — full verifyCrewAccess gate,
 *      owner/co_owner/admin only;
 *   2. password-auth path (PC viewer) — optional actorUserId + isPasswordAuth
 *      echoed from the password session, re-gated against crews.owner_id.
 * When the cookie exists but belongs to a non-owner member, path 2 is NOT
 * tried (the stronger identity wins, same owner-only verdict as before).
 */
async function resolveVerifyOwnerActor(params: {
  slug: string;
  actorUserId?: string;
  isPasswordAuth?: boolean;
  ownerOnlyError: string;
}): Promise<{ ok: boolean; actorChatId?: string; error?: string }> {
  const access = await verifyCrewAccess(params.slug);
  if (access.allowed) {
    if (access.isOwner !== true) {
      return { ok: false, error: params.ownerOnlyError };
    }
    const actorChatId = String(access.actorUserId || "");
    if (!actorChatId) return { ok: false, error: "Не удалось определить пользователя." };
    return { ok: true, actorChatId };
  }
  if (params.isPasswordAuth && params.actorUserId?.trim()) {
    const pw = await verifyPasswordAuthOwnerAccess(params.slug, params.actorUserId.trim());
    if (!pw.ok) return { ok: false, error: pw.error || access.error };
    return { ok: true, actorChatId: params.actorUserId.trim() };
  }
  return { ok: false, error: access.error };
}

export async function adminVerifyRentalAction(params: {
  slug: string;
  rentalId: string;
  /** Password-auth path (PC viewer): owner id from validateAnalyticsPassword. */
  actorUserId?: string;
  /** Password-auth path flag — must come with actorUserId. */
  isPasswordAuth?: boolean;
}): Promise<ActionResponse<AdminVerifyResult>> {
  try {
    // Server-side gate: owner/co_owner/admin only (verifyCrewAccess isOwner
    // covers owner+admin+co_owner — the same gate as the team-salary views);
    // the password session of the crew owner is the second accepted identity.
    const actor = await resolveVerifyOwnerActor({
      slug: params.slug,
      actorUserId: params.actorUserId,
      isPasswordAuth: params.isPasswordAuth,
      ownerOnlyError: "Подтверждать расчёты может владелец или администратор экипажа.",
    });
    if (!actor.ok) return { success: false, error: actor.error };
    const actorChatId = String(actor.actorChatId || "");
    if (!actorChatId) return { success: false, error: "Не удалось определить пользователя." };

    // ── Load the rental (for the snapshot when the row doesn't exist yet) ──
    const { data: rentalRow, error: rentalError } = await supabaseAdmin
      .from("rentals")
      .select(`
        rental_id, crew_id, owner_id, total_cost, metadata, status,
        deposit_amount, deposit_returned,
        created_by_operator_chat_id, created_at,
        requested_start_date, requested_end_date, agreed_start_date, agreed_end_date,
        start_photo_count, end_photo_count,
        vehicle:cars(id, make, model, specs, daily_price, type, crew_id, is_test_result)
      `)
      .eq("rental_id", params.rentalId)
      .maybeSingle();
    if (rentalError) throw rentalError;
    const rental = rentalRow as any;
    if (!rental) return { success: false, error: "Аренда не найдена." };
    // Task 128 hardening: a сверка confirms the money of a CLOSED deal. The
    // CommissionVerificationCard gates the button client-side (isClosed =
    // completed) and the table-view quick-verify now reuses this action too —
    // so the server enforces the same rule as the resend action below: the
    // АРЕНДЫ CSV block also carries in-progress rows (the builder only
    // excludes cancelled), and stamping a сверка on those would be fiction
    // (task126 codereview #1 principle).
    if (rental.status !== "completed") {
      return {
        success: false,
        error: `Сверка заводится только по закрытым арендам (текущий статус: ${rental.status || "неизвестен"}).`,
      };
    }

    // ── Load or create the verification row (shared with the resend action) ──
    let row: RentalVerificationRow;
    let createdNow: boolean;
    try {
      const loaded = await loadOrCreateVerificationRow({
        rental,
        actorChatId,
        source: "admin_manual",
        fallbackSlug: params.slug,
      });
      row = loaded.row;
      createdNow = loaded.created;
    } catch (rowErr: any) {
      const msg = typeof rowErr?.message === "string" ? rowErr.message : "";
      if (msg.includes("Таблица сверок")) return { success: false, error: msg };
      throw rowErr;
    }

    // ── Apply the owner-side confirm through the SAME state machine ──
    // applyVerificationAction refuses a second confirm on verified rows and
    // any foreign chat ids — the single funnel keeps the transitions audited.
    // TASK 102: a co_owner/admin with a DIFFERENT chat id than the recorded
    // owner_chat_id used to bounce off the party check («Вы не участник
    // сверки») while the UI happily showed them the ✅ button. The action is
    // owner-tier gated above, so a non-party authority acts ON THE OWNER
    // SIDE (the docstring's «boss confirms FOR the pair» semantics) instead
    // of failing silently.
    const stateChatId =
      row.operator_chat_id === actorChatId || row.owner_chat_id === actorChatId
        ? actorChatId
        : row.owner_chat_id || actorChatId;
    const result = applyVerificationAction(row, {
      action: "confirm",
      chatId: stateChatId,
      nowIso: new Date().toISOString(),
      reason: undefined,
    });
    if (!result.row) {
      // Not-a-party (owner chat id mismatch) or already verified.
      if (row.status === "verified") {
        return successResponse({ rentalId: params.rentalId, status: "verified" });
      }
      return { success: false, error: result.error || "Действие недоступно." };
    }
    // Admin manual verify is the web equivalent of «both agreed in person»:
    // stamp the operator's side too when it's still missing.
    const finalRow: RentalVerificationRow = {
      ...result.row,
      status: "verified",
      verified_at: result.row.verified_at ?? new Date().toISOString(),
      operator_confirmed_at: result.row.operator_confirmed_at ?? new Date().toISOString(),
      owner_confirmed_at: result.row.owner_confirmed_at ?? new Date().toISOString(),
    };

    const { error: updateError } = await supabaseAdmin
      .from("rental_verifications")
      .update({
        status: finalRow.status,
        operator_confirmed_at: finalRow.operator_confirmed_at,
        owner_confirmed_at: finalRow.owner_confirmed_at,
        verified_at: finalRow.verified_at,
        updated_at: new Date().toISOString(),
      })
      .eq("rental_id", params.rentalId);
    if (updateError) throw updateError;

    logger.info(`[rental-verify] admin manual verify: ${params.rentalId} by ${actorChatId} (created=${createdNow})`);
    grantVerificationAchievements(finalRow, { speedy: false }).catch(() => undefined);

    return successResponse({ rentalId: params.rentalId, status: "verified" });
  } catch (err) {
    logger.error("[rental-verify] adminVerifyRentalAction exception:", err);
    return errorResponse(handleError(err, "adminVerifyRentalAction"));
  }
}

// ── Shared backfill: load the row or build one from current rental data ──────
// Used by BOTH adminVerifyRentalAction and resendVerificationDmsAction so the
// «old rental without a row» case is handled identically (attribution pulled
// from pickup_freeze / return_confirmed_by when metadata is richer than the
// plain snapshot).
async function loadOrCreateVerificationRow(params: {
  rental: any;
  actorChatId: string;
  source: string;
  fallbackSlug: string;
}): Promise<{ row: RentalVerificationRow; created: boolean }> {
  const { data: existing, error: fetchError } = await supabaseAdmin
    .from("rental_verifications")
    .select("*")
    .eq("rental_id", params.rental.rental_id)
    .maybeSingle();
  if (fetchError) {
    const msg = fetchError.message || "";
    if (!/relation .* does not exist|schema cache/i.test(msg) && fetchError.code !== "42P01") throw fetchError;
    throw new Error("Таблица сверок ещё не создана — примените SQL (rental-verifications-table-2026-10-17.sql).");
  }
  if (existing) return { row: existing as RentalVerificationRow, created: false };

  // Task 114: gear/service docs carry no operator bonus — nothing to verify.
  // Same class the auto-trigger skips (rental-verify.ts); a manual tap on a
  // service record must not spawn a pending row that would linger forever.
  const vehicleSkip = Array.isArray(params.rental.vehicle) ? params.rental.vehicle[0] : params.rental.vehicle;
  const metaSkip = (params.rental.metadata || {}) as Record<string, unknown>;
  if (metaSkip.item_type === "equipment" || vehicleSkip?.type === "equipment" || vehicleSkip?.type === "service") {
    throw new Error("Документы услуг и экипировки не требуют сверки — бонуса оператора нет.");
  }

  const nowIso = new Date().toISOString();
  const snapshot = await computeRentalVerificationSnapshot({
    rental: params.rental,
    crewId: params.rental.crew_id,
    requestedAtIso: nowIso,
  });

  // Task 114: audit grade — frozen with the numbers (same as the auto-trigger).
  try {
    let artifact: { total_sum?: number | null; deposit_rub?: number | null } | null = null;
    if (metaSkip.source === "doc_command" && Number(params.rental.total_cost) > 0) {
      const privateSchema = (supabaseAdmin as unknown as { schema: (s: string) => typeof supabaseAdmin }).schema("private");
      const { data: art } = await privateSchema
        .from("rental_contract_artifacts")
        .select("total_sum, deposit_rub")
        .eq("rental_id", params.rental.rental_id)
        .maybeSingle();
      artifact = art || null;
    }
    snapshot.audit = buildAuditStamp(
      computeRentalAuditGrade({
        status: params.rental.status,
        totalCost: params.rental.total_cost,
        depositAmount: params.rental.deposit_amount,
        depositReturned: params.rental.deposit_returned,
        metadata: metaSkip,
        requestedStartDate: params.rental.requested_start_date,
        requestedEndDate: params.rental.requested_end_date,
        agreedStartDate: params.rental.agreed_start_date,
        agreedEndDate: params.rental.agreed_end_date,
        createdByOperatorChatId: params.rental.created_by_operator_chat_id,
        vehicleType: vehicleSkip?.type ?? null,
        isTestResult: (vehicleSkip as any)?.is_test_result === true,
        artifact: artifact ? { totalSum: artifact.total_sum, depositRub: artifact.deposit_rub } : null,
      }),
      nowIso,
      "auto-audit-2026-10-19",
    );
  } catch (auditErr) {
    // Non-fatal: an ungraded row only loses the bulk sweep shortcut.
    logger.warn(`[rental-verify] audit grade failed for ${params.rental.rental_id} (non-fatal):`, auditErr);
  }

  // ── Task 123: reasonability — the same freeze the auto-trigger does, so
  // a drawer-created row collapses its расчёт too when the rental is clean.
  try {
    const reasonability = computeVerificationReasonability({
      audit: {
        grade: snapshot.audit?.grade ?? "almost",
        notes: snapshot.audit?.notes ?? ["аудит не выполнен"],
      },
      markup: Number.isFinite(Number(snapshot.formula?.markup)) ? Number(snapshot.formula?.markup) : null,
      total: Number(snapshot.totalCost) || 0,
      penaltyAmount: Number(snapshot.penalty?.amount) || 0,
      damageNotes: snapshot.damageNotes,
      depositReturned: snapshot.depositReturned,
      depositAmount: Number(params.rental.deposit_amount) || 0,
      hasFormula: !!snapshot.formula && snapshot.formula.standardTotal > 0,
    });
    snapshot.reasonability = { ...reasonability, checkedAt: nowIso };
  } catch (reasonErr) {
    logger.warn(`[rental-verify] reasonability failed for ${params.rental.rental_id} (non-fatal):`, reasonErr);
  }

  // ── TASK158: the generated split + the operator party ──
  // The сверка addresses ONE operator = the TOP shareholder of the generated
  // role split (создал/выдал/принял, equal weight per filled role); the
  // full «👥 ЗП по долям» line rides the frozen snapshot.salarySplit.
  const createdAtMs = Date.parse(String(params.rental.created_at || "")) || Date.now();
  const { data: shiftRows } = await supabaseAdmin
    .from("crew_member_shifts")
    .select("member_id, clock_in_time, clock_out_time")
    .eq("crew_id", params.rental.crew_id)
    .gte("clock_in_time", new Date(createdAtMs - 25 * 3600 * 1000).toISOString())
    .lte("clock_in_time", new Date(createdAtMs + 25 * 3600 * 1000).toISOString());
  const splitShifts = (shiftRows || []).map((s: { member_id: string; clock_in_time: string; clock_out_time: string | null }) => ({
    member_id: s.member_id,
    clock_in_time: s.clock_in_time,
    clock_out_time: s.clock_out_time ?? null,
  }));
  const splitInput = {
    created_by_operator_chat_id: params.rental.created_by_operator_chat_id,
    created_at: params.rental.created_at,
    metadata: metaSkip,
  };
  const { shares } = resolveRentalOperatorSplit(splitInput, splitShifts);
  const topShare = resolveRentalOperator(splitInput, splitShifts);
  snapshot.salarySplit = buildSnapshotSalarySplit(Number(snapshot.total) || 0, shares);

  const { data: crewRow } = await supabaseAdmin
    .from("crews")
    .select("slug")
    .eq("id", params.rental.crew_id)
    .maybeSingle();
  const meta = (params.rental.metadata || {}) as Record<string, unknown>;
  const freeze = meta.pickup_freeze as Record<string, unknown> | undefined;
  const insert = {
    rental_id: params.rental.rental_id,
    crew_id: params.rental.crew_id,
    crew_slug: (crewRow?.slug as string) || params.fallbackSlug,
    operator_chat_id: topShare.operatorId
      ? String(topShare.operatorId)
      : typeof params.rental.created_by_operator_chat_id === "string" && params.rental.created_by_operator_chat_id.trim()
        ? params.rental.created_by_operator_chat_id.trim()
        : null,
    owner_chat_id: params.rental.owner_id ? String(params.rental.owner_id) : null,
    requested_by: params.actorChatId,
    status: "pending" as const,
    snapshot: {
      ...snapshot,
      attribution: {
        ...snapshot.attribution,
        handedByChatId:
          freeze && typeof freeze.frozen_by === "string" && freeze.frozen_by.trim()
            ? freeze.frozen_by.trim()
            : null,
        returnedByChatId:
          typeof meta.return_confirmed_by === "string" && meta.return_confirmed_by.trim()
            ? meta.return_confirmed_by.trim()
            : null,
      },
    },
    source: params.source,
  };
  const { data: created, error: insertError } = await supabaseAdmin
    .from("rental_verifications")
    .upsert(insert, { onConflict: "rental_id", ignoreDuplicates: true })
    .select("*")
    .maybeSingle();
  if (insertError) throw insertError;
  if (created) return { row: created as RentalVerificationRow, created: true };
  // Lost a race — re-read.
  const { data: reread } = await supabaseAdmin
    .from("rental_verifications")
    .select("*")
    .eq("rental_id", params.rental.rental_id)
    .maybeSingle();
  if (!reread) throw new Error("Не удалось создать запись сверки.");
  return { row: reread as RentalVerificationRow, created: false };
}

