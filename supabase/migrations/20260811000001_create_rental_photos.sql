-- ─── 4. Path-based access check function (for RLS) ────────────────────────
-- storage.objects doesn't have a rental_id column, so we parse it from the
-- file path. The path schema is: '<rental_id>/<start|end>/<file>.jpg'
-- so the first path segment is the rental_id.
--
-- The function checks if the given user_id is authorized to access that rental:
--   1. Is the user the renter? (rentals.user_id = user_id)
--   2. Is the user a crew member of the bike's crew? (crew_members join)
-- If either is true, return true.
CREATE OR REPLACE FUNCTION public.can_access_rental_photo(
  object_path TEXT,
  user_id TEXT
) RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  path_rental_id TEXT;
  rental_row RECORD;
BEGIN
  -- Path schema: '<rental_id>/<start|end>/<file>.jpg'
  -- Split on '/' and take the first segment.
  path_rental_id := split_part(object_path, '/', 1);

  -- If the path doesn't parse to a UUID, deny.
  IF path_rental_id !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
    RETURN FALSE;
  END IF;

  -- Fetch the rental + vehicle crew_id in one shot
  SELECT
    r.user_id,
    r.owner_id,
    c.crew_id
  INTO rental_row
  FROM public.rentals r
  LEFT JOIN public.cars c ON c.id = r.vehicle_id
  WHERE r.rental_id = path_rental_id::uuid;

  IF NOT FOUND THEN
    RETURN FALSE;
  END IF;

  -- Check 1: is the user the renter or owner?
  IF rental_row.user_id = user_id OR rental_row.owner_id = user_id THEN
    RETURN TRUE;
  END IF;

  -- Check 2: is the user a crew member of the bike's crew?
  IF rental_row.crew_id IS NOT NULL THEN
    PERFORM 1
    FROM public.crew_members
    WHERE crew_id = rental_row.crew_id
      AND user_id = user_id
      AND membership_status = 'active'
      AND role IN ('owner', 'admin', 'co_owner', 'member');
    IF FOUND THEN
      RETURN TRUE;
    END IF;
  END IF;

  RETURN FALSE;
END;
$$;

GRANT EXECUTE ON FUNCTION public.can_access_rental_photo(TEXT, TEXT) TO service_role, anon, authenticated;


-- ─── 5. RLS on storage.objects for rental-photos bucket ────────────────────
-- Note: Supabase Storage RLS uses `auth.jwt() ->> 'sub'` for the user_id
-- (NOT auth.uid() — that's for table RLS). However, for the service-role-only
-- INSERT/DELETE pattern we use, the policies are simpler:
--
-- SELECT: allow if can_access_rental_photo returns true (renter or crew member)
-- INSERT: service role only (uploads go through server actions using supabaseAdmin)
-- DELETE: service role only (only the retention cron deletes)
--
-- The SELECT policy uses a SECURITY DEFINER function call so it works for
-- authenticated users (renter using WebApp) without exposing the join logic.
--
-- NOTE: storage RLS policies match on `bucket_id = 'rental-photos'`.

-- Drop existing policies if re-running (DO block guards against PG < 15)
DO $$
BEGIN
  -- SELECT policy
  BEGIN
    DROP POLICY IF EXISTS "rental-photos select for authorized users"
      ON storage.objects;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;

  BEGIN
    CREATE POLICY "rental-photos select for authorized users"
      ON storage.objects FOR SELECT
      USING (
        bucket_id = 'rental-photos'
        AND public.can_access_rental_photo(
          name,
          coalesce(auth.jwt() ->> 'sub', '')
        )
      );
  EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'SELECT policy create skipped: %', SQLERRM;
  END;

  -- INSERT policy — service role only
  BEGIN
    DROP POLICY IF EXISTS "rental-photos insert service role only"
      ON storage.objects;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;

  BEGIN
    CREATE POLICY "rental-photos insert service role only"
      ON storage.objects FOR INSERT
      WITH CHECK (
        bucket_id = 'rental-photos'
        AND auth.role() = 'service_role'
      );
  EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'INSERT policy create skipped: %', SQLERRM;
  END;

  -- DELETE policy — service role only
  BEGIN
    DROP POLICY IF EXISTS "rental-photos delete service role only"
      ON storage.objects;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;

  BEGIN
    CREATE POLICY "rental-photos delete service role only"
      ON storage.objects FOR DELETE
      USING (
        bucket_id = 'rental-photos'
        AND auth.role() = 'service_role'
      );
  EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'DELETE policy create skipped: %', SQLERRM;
  END;
END
$$;


