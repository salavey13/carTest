-- ─── 2. Metadata table ─────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.rental_photos (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  rental_id       UUID NOT NULL REFERENCES public.rentals(rental_id) ON DELETE CASCADE,

  -- 'start' = ДО (handoff photo, before rental starts)
  -- 'end'   = ПОСЛЕ (return photo, after rental ends)
  photo_type      TEXT NOT NULL CHECK (photo_type IN ('start', 'end')),

  -- Full path in the bucket: '<rental_id>/<start|end>/<seq>-<timestamp>-<uploader>.jpg'
  storage_path    TEXT NOT NULL,

  -- Post-compression metadata (for audit + storage budgeting)
  file_size_bytes INTEGER NOT NULL,
  sha256_hash     TEXT NOT NULL,         -- tamper detection + dedup
  mime_type       TEXT NOT NULL DEFAULT 'image/jpeg',
  width           INTEGER,               -- pixels, post-compression (nullable for legacy)
  height          INTEGER,               -- pixels, post-compression (nullable for legacy)

  -- Audit: who uploaded + through which surface
  uploaded_by     TEXT NOT NULL REFERENCES users(user_id) ON DELETE SET NULL,
  uploader_role   TEXT NOT NULL CHECK (uploader_role IN ('renter', 'operator', 'admin', 'owner', 'bot')),
  source          TEXT NOT NULL DEFAULT 'webapp' CHECK (source IN ('webapp', 'bot', 'operator_ui', 'drag_drop')),

  -- For soft delete (Phase 4 retention cron hard-deletes after 30 days in trash)
  archived_at     TIMESTAMPTZ,           -- set when moved to rental-photos-archive bucket
  deleted_at      TIMESTAMPTZ,           -- set when soft-deleted (moved to _trash/ prefix)

  -- EXIF + device info (GPS stripped in v1; opt-in deferred to I4)
  metadata        JSONB DEFAULT '{}'::jsonb,

  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes for the common query patterns
